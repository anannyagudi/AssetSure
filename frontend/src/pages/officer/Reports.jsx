import React, { useEffect, useState } from 'react';
import { OfficerLayout } from '../../layouts/DashboardLayout';
import { SectionHeader, Spinner, EmptyState } from '../../components/UI';
import { getReports, generateReport } from '../../services/api';
import { useToast } from '../../context/ToastContext';
import { FileText, Download } from 'lucide-react';

const OfficerReports = () => {
    const [reports, setReports] = useState([]);
    const [loading, setLoading] = useState(true);
    const addToast = useToast();

    useEffect(() => {
        getReports().then(r => setReports(r.data)).catch(console.error).finally(() => setLoading(false));
    }, []);

    return (
        <OfficerLayout>
            <SectionHeader title="Reports" subtitle="All generated verification and monitoring reports." />
            {loading ? <div className="flex justify-center py-20"><Spinner size={36} /></div>
            : reports.length === 0 ? <EmptyState icon={FileText} title="No Reports" description="Generate reports from individual verification detail pages." />
            : (
                <div className="card overflow-hidden p-0">
                    <table className="w-full">
                        <thead style={{ backgroundColor: 'var(--bg-input)', borderBottom: '1px solid var(--border)' }}>
                            <tr>{['Report ID', 'Type', 'Borrower', 'Asset', 'Generated By', 'Date', 'PDF'].map(h => <th key={h} className="th">{h}</th>)}</tr>
                        </thead>
                        <tbody>
                            {reports.map(r => (
                                <tr key={r._id} className="table-row">
                                    <td className="td font-mono text-xs text-primary-500">{r.reportId}</td>
                                    <td className="td text-xs">{r.reportType}</td>
                                    <td className="td">{r.borrower?.name}</td>
                                    <td className="td">{r.asset?.machineName}</td>
                                    <td className="td text-xs">{r.generatedBy?.name || 'System'}</td>
                                    <td className="td text-xs">{r.generatedAt ? new Date(r.generatedAt).toLocaleDateString() : '—'}</td>
                                    <td className="td">
                                        {r.pdfUrl && (
                                            <a href={r.pdfUrl} target="_blank" rel="noopener noreferrer" className="btn-secondary text-xs !py-1 !px-2">
                                                <Download size={12} /> PDF
                                            </a>
                                        )}
                                    </td>
                                </tr>
                            ))}
                        </tbody>
                    </table>
                </div>
            )}
        </OfficerLayout>
    );
};

export default OfficerReports;
